def seed(project_id: int = 1) -> None:
    """Idempotently insert MEL_INDICATORS and MEL_INDICATOR_TARGETS for
    *project_id*. Safe to call on every app boot: existing rows are left
    untouched (matched on indicator_id for indicators, on
    (indicator_id, fiscal_year, quarter) for targets)."""
    n_ind = 0
    for ind in MEL_INDICATORS:
        existing = run_query(
            "SELECT id FROM mel_indicators WHERE project_id=:pid AND indicator_id=:iid",
            {"pid": project_id, "iid": ind["indicator_id"]},
        )
        if existing:
            continue
        run_write(
            """INSERT INTO mel_indicators
               (project_id, indicator_id, level, statement, unit_of_measure,
                fish_type, aggregation_type, model_sheet, cel_scope,
                means_of_verification, responsible_collect, responsible_verify,
                responsible_review, planner_reference, source_doc, source_page)
               VALUES (:project_id, :indicator_id, :level, :statement, :unit_of_measure,
                       :fish_type, :aggregation_type, :model_sheet, :cel_scope,
                       :means_of_verification, :responsible_collect, :responsible_verify,
                       :responsible_review, :planner_reference, :source_doc, :source_page)""",
            {"project_id": project_id, **ind},
        )
        n_ind += 1

    id_map = {
        r["indicator_id"]: r["id"]
        for r in run_query(
            "SELECT id, indicator_id FROM mel_indicators WHERE project_id=:pid",
            {"pid": project_id},
        )
    }

    n_tgt = 0
    for indicator_id, fiscal_year, quarter, target_value, phasing_confirmed in MEL_INDICATOR_TARGETS:
        mel_id = id_map.get(indicator_id)
        if mel_id is None:
            continue  # indicator row failed to seed; don't orphan a target
        existing = run_query(
            "SELECT id FROM mel_indicator_targets WHERE indicator_id=:iid AND fiscal_year=:fy AND quarter=:q",
            {"iid": mel_id, "fy": fiscal_year, "q": quarter},
        )
        if existing:
            continue
        run_write(
            """INSERT INTO mel_indicator_targets
               (indicator_id, project_id, fiscal_year, quarter, target_value, phasing_confirmed)
               VALUES (:indicator_id, :project_id, :fiscal_year, :quarter, :target_value, :phasing_confirmed)""",
            {
                "indicator_id": mel_id,
                "project_id": project_id,
                "fiscal_year": fiscal_year,
                "quarter": quarter,
                "target_value": target_value,
                "phasing_confirmed": phasing_confirmed,
            },
        )
        n_tgt += 1

    print(f"mel_indicators: {n_ind} inserted ({len(MEL_INDICATORS) - n_ind} already present).")
    print(f"mel_indicator_targets: {n_tgt} inserted ({len(MEL_INDICATOR_TARGETS) - n_tgt} already present).")
