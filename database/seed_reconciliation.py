def _seed_org(org: str, lines: list[tuple], project_id: int) -> int:
    existing_codes = {
        r["reconciliation_code"] for r in run_query(
            "SELECT reconciliation_code FROM mel_reconciliation_lines "
            "WHERE project_id=:pid AND submitting_org=:org",
            {"pid": project_id, "org": org},
        )
    }
    n = 0
    for (code, old_code, label, unit, y1, q2, q3, q4,
         fish_split, cel_id) in lines:
        if code in existing_codes:
            continue
        line_id = insert_returning_id(
            """INSERT INTO mel_reconciliation_lines
               (project_id, submitting_org, reconciliation_code, indicator_label,
                unit, old_planner_code, cel_indicator_id, fish_type_split,
                aggregation_type)
               VALUES (:pid, :org, :code, :label, :unit, :old_code, :cel_id,
                       :fish_split, 'Incremental')""",
            {
                "pid": project_id, "org": org, "code": code, "label": label,
                "unit": unit, "old_code": old_code, "cel_id": cel_id,
                # A plain Python bool, not int(...) -- SQLAlchemy/psycopg map
                # it to Postgres's native BOOLEAN column correctly; passing
                # 0/1 (a Postgres smallint literal) fails there with
                # "column is of type boolean but expression is of type
                # smallint" (fish_type_split is INTEGER CHECK(0,1) in
                # schema.sql/SQLite but BOOLEAN in schema_postgres.sql, same
                # as mel_indicator_actuals.completeness_checked's existing
                # pattern in pages/13_M_IPTT.py).
                "fish_split": bool(fish_split),
            },
        )
        # Quarterly targets: CEL rows have no known phasing (whole Y1
        # figure goes under Q4 -- see this module's and schema.sql's
        # comments); TechnoServe rows use their real Q2-Q4 workplan split.
        # Either way, only non-null quarters are inserted -- a missing row
        # reads back as None, same as an explicitly-null one.
        quarters = (None, q2, q3, q4) if org == "TechnoServe" else (None, None, None, y1)
        for q, val in zip((1, 2, 3, 4), quarters):
            if val is None:
                continue
            run_write(
                """INSERT INTO mel_reconciliation_targets
                   (line_id, project_id, fiscal_year, quarter, target_value)
                   VALUES (:lid, :pid, :fy, :q, :val)""",
                {"lid": line_id, "pid": project_id, "fy": FISCAL_YEAR, "q": q, "val": val},
            )
        n += 1
    return n


def seed(project_id: int | None = None) -> None:
    """Idempotently insert the 12 CEL + 10 TechnoServe reconciliation lines
    (and their Y1 FY2026 targets) for *project_id*. Safe to call on every
    app boot: a line already present (by submitting_org + reconciliation_code)
    is left untouched, including any in-app edits to its actuals/notes.

    project_id=None (the default) looks up the SAWA project by name, same
    as every other seed_*.py module."""
    if project_id is None:
        existing_project = run_query(
            "SELECT project_id FROM projects WHERE name = 'SAWA'", {}
        )
        if not existing_project:
            print("Reconciliation lines: skipped (no 'SAWA' row in projects yet).")
            return
        project_id = existing_project[0]["project_id"]

    n_cel = _seed_org("CEL", CEL_LINES, project_id)
    n_tns = _seed_org("TechnoServe", TNS_LINES, project_id)
    print(f"Reconciliation lines: {n_cel} CEL, {n_tns} TechnoServe inserted.")
